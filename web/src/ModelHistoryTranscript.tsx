import { useCallback, useEffect, useLayoutEffect, useMemo, useRef, useState } from 'react';
import { ActionIcon, Badge, Box, Button, Divider, Group, ScrollArea, Stack, Switch, Text, TextInput } from '@mantine/core';
import { IconArrowDown, IconArrowsMaximize, IconChevronDown, IconChevronRight, IconCopy, IconSearch } from '@tabler/icons-react';
import { getImpactInference, type ImpactInferenceRecord } from './api';

type Props = {
  runId: string | null;
  emptyText?: string;
  onFullScreen?: () => void;
  showHeader?: boolean;
};

const PAGE_SIZE = 50;
const USER_ORIGINS = new Set(['user_custom']);

type Cursor = { before: string; before_id: string };

function mergeRecords(current: ImpactInferenceRecord[], incoming: ImpactInferenceRecord[]) {
  const byId = new Map(current.map((record) => [record.id, record]));
  for (const record of incoming) byId.set(record.id, record);
  return Array.from(byId.values()).sort((a, b) => a.created_at.localeCompare(b.created_at) || a.id.localeCompare(b.id));
}

function stamp(value: string) {
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? value : date.toLocaleString();
}

function GeneratedInputs({ record, showAll }: { record: ImpactInferenceRecord; showAll: boolean }) {
  const [expanded, setExpanded] = useState(false);
  const generated = record.inputs.filter((input) => !USER_ORIGINS.has(input.input_origin));
  if (!generated.length) return null;
  return (
    <Stack gap={5}>
      {!showAll && (
        <Button size="compact-xs" variant="subtle" color="gray" style={{ alignSelf: 'flex-start' }} leftSection={expanded ? <IconChevronDown size={13} /> : <IconChevronRight size={13} />} onClick={() => setExpanded((value) => !value)}>
          {generated.length} autogenerated {generated.length === 1 ? 'input' : 'inputs'} hidden
        </Button>
      )}
      {(showAll || expanded) && generated.map((input) => (
        <Box key={`${input.sequence_no}:${input.input_source}`} pl="sm" style={{ borderLeft: '2px solid var(--mantine-color-default-border)' }}>
          <Text size="xs" c="dimmed">{input.label || input.input_source} · {input.input_origin}</Text>
          <Text size="sm" style={{ whiteSpace: 'pre-wrap', overflowWrap: 'anywhere' }}>{input.content}</Text>
        </Box>
      ))}
    </Stack>
  );
}

function jsonResponse(value: string) {
  const trimmed = value.trim();
  const candidates = [trimmed, trimmed.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, ''), trimmed.replace(/^[\s\S]*?\bJSON\s*\n?/i, '')];
  for (const candidate of candidates) {
    const start = candidate.search(/[\[{]/);
    if (start < 0) continue;
    const prefix = candidate.slice(0, start).trim();
    if (prefix && !/^(?:ChatGPT said:?)?\s*JSON\s*:?$/i.test(prefix)) continue;
    try {
      const parsed: unknown = JSON.parse(candidate.slice(start));
      if (parsed !== null && typeof parsed === 'object') return parsed;
    } catch {
      continue;
    }
  }
  return null;
}

function TranscriptExchange({ record, showGenerated }: { record: ImpactInferenceRecord; showGenerated: boolean }) {
  const [details, setDetails] = useState(false);
  const [responseExpanded, setResponseExpanded] = useState(false);
  const userInputs = useMemo(() => record.inputs.filter((input) => USER_ORIGINS.has(input.input_origin)).sort((a, b) => a.sequence_no - b.sequence_no), [record.inputs]);
  const response = record.response_text || '';
  const parsedJson = useMemo(() => jsonResponse(response), [response]);
  const jsonSummary = useMemo(() => {
    if (parsedJson === null) return '';
    if (Array.isArray(parsedJson)) return `JSON array · ${parsedJson.length} items`;
    const object = parsedJson as Record<string, unknown>;
    const operations = object.operations;
    if (Array.isArray(operations)) return `JSON changeset · ${operations.length} operations${typeof object.description === 'string' ? ` · ${object.description}` : ''}`;
    return `JSON object · ${Object.keys(object).length} fields`;
  }, [parsedJson]);
  const color = record.status === 'failed' ? 'red' : record.status === 'completed' ? 'green' : 'yellow';
  return (
    <Box data-invocation-id={record.id} py="sm" style={{ minWidth: 0 }}>
      <Group gap={6} justify="space-between" align="center" mb={6}>
        <Group gap={7} wrap="wrap">
          <Text size="xs" fw={650}>{record.stage_type || 'Inference'}</Text>
          <Badge size="xs" color={color} variant="light">{record.status}</Badge>
          <Text size="xs" c="dimmed">{record.provider} · {record.model}</Text>
        </Group>
        <Text size="xs" c="dimmed">{stamp(record.created_at)}</Text>
      </Group>
      <Stack gap="xs">
        <Box>
          <Text size="xs" fw={650} c="dimmed" mb={4}>Input</Text>
          {userInputs.map((input) => (
            <Box key={`${input.sequence_no}:${input.input_source}`} mb={5}>
              {userInputs.length > 1 && <Text size="xs" c="dimmed">{input.label}</Text>}
              <Text size="sm" style={{ whiteSpace: 'pre-wrap', overflowWrap: 'anywhere' }}>{input.content}</Text>
            </Box>
          ))}
          {userInputs.length === 0 && <Text size="xs" c="dimmed">No user-authored input recorded</Text>}
          <GeneratedInputs key={record.id} record={record} showAll={showGenerated} />
        </Box>
        <Box>
          <Group gap={6} justify="space-between" align="center" mb={4}>
            <Text size="xs" fw={650} c="dimmed">Model response</Text>
            {response && <ActionIcon size="xs" variant="subtle" color="gray" aria-label="Copy response" onClick={() => void navigator.clipboard.writeText(response)}><IconCopy size={13} /></ActionIcon>}
          </Group>
          {response ? (
            parsedJson !== null ? (
              <Stack gap={6}>
                <Button size="compact-sm" variant="subtle" color="gray" style={{ alignSelf: 'flex-start', maxWidth: '100%' }} leftSection={responseExpanded ? <IconChevronDown size={14} /> : <IconChevronRight size={14} />} onClick={() => setResponseExpanded((value) => !value)}>
                  <Text size="xs" truncate>{jsonSummary}</Text>
                </Button>
                {responseExpanded && <Box component="pre" p="sm" style={{ margin: 0, fontSize: 12, whiteSpace: 'pre-wrap', overflowWrap: 'anywhere', maxHeight: 600, overflowY: 'auto', background: 'var(--mantine-color-default-hover)', borderRadius: 6 }}>{JSON.stringify(parsedJson, null, 2)}</Box>}
              </Stack>
            ) : (
              <Text size="sm" style={{ whiteSpace: 'pre-wrap', overflowWrap: 'anywhere' }}>{response}</Text>
            )
          ) : <Text size="xs" c="dimmed">{record.status === 'failed' ? record.error_message || 'Invocation failed' : 'No response recorded'}</Text>}
        </Box>
        <Button size="compact-xs" variant="subtle" color="gray" style={{ alignSelf: 'flex-start' }} leftSection={details ? <IconChevronDown size={12} /> : <IconChevronRight size={12} />} onClick={() => setDetails((value) => !value)}>Details</Button>
        {details && (
          <Box p="xs" style={{ border: '1px solid var(--mantine-color-default-border)', borderRadius: 6 }}>
            <Text size="xs" c="dimmed">Invocation: {record.id}</Text>
            <Text size="xs" c="dimmed">Session: {record.inference_session_id}</Text>
            <Text size="xs" c="dimmed">Transport: {record.transport}</Text>
            <Text size="xs" c="dimmed">Step: {record.step_id}</Text>
            <Text size="xs" c="dimmed">Input tokens: {record.input_tokens ?? '—'} · Output tokens: {record.output_tokens ?? '—'}</Text>
            {record.error_message && <Text size="xs" c="red">{record.error_message}</Text>}
            {record.response_payload != null && <Box component="pre" style={{ fontSize: 11, whiteSpace: 'pre-wrap', overflowWrap: 'anywhere' }}>{JSON.stringify(record.response_payload, null, 2)}</Box>}
          </Box>
        )}
      </Stack>
      <Divider mt="md" />
    </Box>
  );
}

export function ModelHistoryTranscript({ runId, emptyText = 'No recorded model invocations', onFullScreen, showHeader = true }: Props) {
  const [records, setRecords] = useState<ImpactInferenceRecord[]>([]);
  const [hasMore, setHasMore] = useState(false);
  const [loading, setLoading] = useState(false);
  const [loadingOlder, setLoadingOlder] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [showGenerated, setShowGenerated] = useState(false);
  const [search, setSearch] = useState('');
  const [atBottom, setAtBottom] = useState(true);
  const viewportRef = useRef<HTMLDivElement>(null);
  const requestRef = useRef(0);
  const pendingOlder = useRef(false);
  const restoring = useRef<{ height: number; top: number } | null>(null);
  const initialized = useRef(false);
  const recordsRef = useRef<ImpactInferenceRecord[]>([]);
  const hasMoreRef = useRef(false);
  const loadingRef = useRef(false);
  const scrollToLatest = useCallback(() => {
    const viewport = viewportRef.current;
    if (viewport) viewport.scrollTop = viewport.scrollHeight;
    setAtBottom(true);
  }, []);

  useEffect(() => {
    requestRef.current += 1;
    const request = requestRef.current;
    initialized.current = false;
    recordsRef.current = [];
    hasMoreRef.current = false;
    pendingOlder.current = false;
    restoring.current = null;
    setRecords([]);
    setHasMore(false);
    setError(null);
    setAtBottom(true);
    if (!runId) return;
    setLoading(true);
    getImpactInference(runId, { limit: PAGE_SIZE }).then((result) => {
      if (request !== requestRef.current) return;
      const next = mergeRecords([], result.invocations);
      recordsRef.current = next;
      hasMoreRef.current = result.has_more;
      setRecords(next);
      setHasMore(result.has_more);
      initialized.current = true;
    }).catch((reason) => {
      if (request === requestRef.current) setError(String(reason));
    }).finally(() => {
      if (request === requestRef.current) setLoading(false);
    });
    return () => { requestRef.current += 1; };
  }, [runId]);

  useLayoutEffect(() => {
    const viewport = viewportRef.current;
    if (!viewport) return;
    if (restoring.current) {
      const previous = restoring.current;
      viewport.scrollTop = previous.top + viewport.scrollHeight - previous.height;
      restoring.current = null;
      return;
    }
    if (initialized.current && atBottom) viewport.scrollTop = viewport.scrollHeight;
  }, [records, atBottom]);

  const loadOlder = useCallback(async () => {
    if (!runId || pendingOlder.current || !hasMoreRef.current || loadingRef.current) return;
    const oldest = recordsRef.current[0];
    if (!oldest) return;
    const request = requestRef.current;
    pendingOlder.current = true;
    loadingRef.current = true;
    setLoadingOlder(true);
    const viewport = viewportRef.current;
    if (viewport) restoring.current = { top: viewport.scrollTop, height: viewport.scrollHeight };
    try {
      const cursor: Cursor = { before: oldest.created_at, before_id: oldest.id };
      const result = await getImpactInference(runId, { ...cursor, limit: PAGE_SIZE });
      if (request !== requestRef.current) return;
      const next = mergeRecords(recordsRef.current, result.invocations);
      recordsRef.current = next;
      hasMoreRef.current = result.has_more;
      setHasMore(result.has_more);
      setRecords(next);
      if (result.invocations.length === 0) restoring.current = null;
    } catch (reason) {
      if (request === requestRef.current) {
        restoring.current = null;
        setError(String(reason));
      }
    } finally {
      if (request === requestRef.current) {
        loadingRef.current = false;
        pendingOlder.current = false;
        setLoadingOlder(false);
      }
    }
  }, [runId]);

  useEffect(() => {
    if (!runId) return;
    const request = requestRef.current;
    const timer = window.setInterval(() => {
      if (!initialized.current || pendingOlder.current || loadingRef.current) return;
      void getImpactInference(runId, { limit: PAGE_SIZE }).then((result) => {
        if (request !== requestRef.current) return;
        const previous = recordsRef.current;
        const next = mergeRecords(previous, result.invocations);
        const changed = next.length !== previous.length || next.some((record, index) => record !== previous[index]);
        if (changed) {
          recordsRef.current = next;
          setRecords(next);
        }
        if (previous.length === 0) {
          hasMoreRef.current = result.has_more;
          setHasMore(result.has_more);
        }
      }).catch(() => undefined);
    }, 5000);
    return () => window.clearInterval(timer);
  }, [runId]);

  const visible = useMemo(() => {
    const term = search.trim().toLowerCase();
    if (!term) return records;
    return records.filter((record) => [record.stage_type, record.provider, record.model, record.response_text || '', ...record.inputs.map((input) => input.content)].some((value) => value.toLowerCase().includes(term)));
  }, [records, search]);

  const handleScroll = useCallback((position: { y: number }) => {
    const viewport = viewportRef.current;
    if (!viewport) return;
    const bottom = viewport.scrollHeight - position.y - viewport.clientHeight < 96;
    setAtBottom(bottom);
    if (position.y < 160 && !search.trim()) void loadOlder();
  }, [loadOlder, search]);

  return (
    <Stack gap="xs" h="100%" style={{ minHeight: 0, minWidth: 0 }}>
      <Group justify="space-between" align="center" gap="xs" wrap="wrap">
        <Group gap="xs" align="center">
          {showHeader && <Text fw={600}>Model history</Text>}
          <Badge variant="light" color="gray" size="sm">{records.length}{hasMore ? '+' : ''} exchanges</Badge>
        </Group>
        <Group gap="md" align="center" wrap="wrap">
          <Switch size="xs" label="Generated inputs" checked={showGenerated} onChange={(event) => setShowGenerated(event.currentTarget.checked)} />
          {onFullScreen && <Button size="xs" variant="subtle" color="gray" leftSection={<IconArrowsMaximize size={14} />} onClick={onFullScreen}>Full screen</Button>}
        </Group>
      </Group>
      <TextInput size="xs" placeholder="Search loaded history" leftSection={<IconSearch size={13} />} value={search} onChange={(event) => setSearch(event.currentTarget.value)} />
      {error && <Text size="xs" c="red">{error}</Text>}
      <Box style={{ flex: 1, minHeight: 0, position: 'relative' }}>
        <ScrollArea h="100%" viewportRef={viewportRef} onScrollPositionChange={handleScroll} offsetScrollbars type="auto">
          <Stack gap={0} pr="xs">
            {loading && <Text size="xs" c="dimmed" py="sm">Loading model history…</Text>}
            {!loading && hasMore && !search.trim() && <Button size="compact-xs" variant="subtle" color="gray" loading={loadingOlder} onClick={() => void loadOlder()}>Load earlier exchanges</Button>}
            {!loading && records.length === 0 && <Text size="sm" c="dimmed" py="sm">{emptyText}</Text>}
            {visible.map((record, index) => {
              const previous = visible[index - 1];
              const sessionChanged = !previous || previous.inference_session_id !== record.inference_session_id;
              return (
                <Box key={record.id}>
                  {sessionChanged && <Group gap="xs" py="xs"><Divider style={{ flex: 1 }} /><Text size="xs" c="dimmed">Session {record.inference_session_id.slice(0, 8)}</Text><Divider style={{ flex: 1 }} /></Group>}
                  <TranscriptExchange record={record} showGenerated={showGenerated} />
                </Box>
              );
            })}
            {!loading && visible.length === 0 && records.length > 0 && <Text size="xs" c="dimmed" py="sm">No matching exchanges in loaded history</Text>}
          </Stack>
        </ScrollArea>
        {!atBottom && <Button size="compact-sm" variant="filled" color="dark" leftSection={<IconArrowDown size={14} />} onClick={scrollToLatest} style={{ position: 'absolute', bottom: 12, right: 18, zIndex: 2, boxShadow: '0 2px 12px rgba(0,0,0,0.3)' }}>Latest</Button>}
      </Box>
    </Stack>
  );
}
